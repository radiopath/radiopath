package hf

import "math"

// magfit calculates the magnetic dip and the gyrofrequency at a control point
// for a height of 100 or 300 km (ITU-R P.1239 section 2, eqs (5)-(11)).
func magfit(here *controlPt, height float64) {
	var p, dp [7][7]float64
	p[0][0] = 1.0

	g := [7][7]float64{
		{0.000000, 0.304112, 0.024035, -0.031518, -0.041794, 0.016256, -0.019523},
		{0.000000, 0.021474, -0.051253, 0.062130, -0.045298, -0.034407, -0.004853},
		{0.000000, 0.000000, -0.013381, -0.024898, -0.021795, -0.019447, 0.003212},
		{0.000000, 0.000000, 0.000000, -.0064960, 0.007008, -0.000608, 0.021413},
		{0.000000, 0.000000, 0.000000, 0.000000, -0.002044, 0.002775, 0.001051},
		{0.000000, 0.000000, 0.000000, 0.000000, 0.000000, 0.000697, 0.000227},
		{0.000000, 0.000000, 0.000000, 0.000000, 0.000000, 0.000000, 0.001115},
	}

	h := [7][7]float64{
		{0.000000, 0.000000, 0.000000, 0.000000, 0.000000, 0.000000, 0.000000},
		{0.000000, -0.057989, 0.033124, 0.014870, -0.011825, -0.000796, -0.005758},
		{0.000000, 0.000000, -0.001579, -0.004075, 0.010006, -0.002000, -0.008735},
		{0.000000, 0.000000, 0.000000, 0.000210, 0.000430, 0.004597, -0.003406},
		{0.000000, 0.000000, 0.000000, 0.000000, 0.001385, 0.002421, -0.000118},
		{0.000000, 0.000000, 0.000000, 0.000000, 0.000000, -0.001218, -0.001116},
		{0.000000, 0.000000, 0.000000, 0.000000, 0.000000, 0.000000, -0.000325},
	}

	ct := [7][7]float64{
		{0.0000000, 0.0000000, 0.33333333, 0.266666666, 0.25714286, 0.25396825, 0.25252525},
		{0.0000000, 0.0000000, 0.00000000, 0.200000000, 0.22857142, 0.23809523, 0.24242424},
		{0.0000000, 0.0000000, 0.00000000, 0.000000000, 0.14285714, 0.19047619, 0.21212121},
		{0.0000000, 0.0000000, 0.00000000, 0.000000000, 0.00000000, 0.11111111, 0.16161616},
		{0.0000000, 0.0000000, 0.00000000, 0.000000000, 0.00000000, 0.00000000, 0.09090909},
		{0.0000000, 0.0000000, 0.00000000, 0.000000000, 0.00000000, 0.00000000, 0.00000000},
		{0.0000000, 0.0000000, 0.00000000, 0.000000000, 0.00000000, 0.00000000, 0.00000000},
	}

	hr := 0 // height index

	ar := r0 / (r0 + height)

	fz := 0.0
	fx := 0.0
	fy := 0.0

	for n := 1; n <= 6; n++ {
		sumz := 0.0
		sumx := 0.0
		sumy := 0.0

		for m := 0; m <= n; m++ {
			if n == m {
				p[m][n] = math.Cos(here.L.lat) * p[m-1][n-1]
				dp[m][n] = math.Cos(here.L.lat)*dp[m-1][n-1] + math.Sin(here.L.lat)*p[m-1][n-1]
			} else if n != 1 {
				p[m][n] = math.Sin(here.L.lat)*p[m][n-1] - ct[m][n]*p[m][n-2]
				dp[m][n] = math.Sin(here.L.lat)*dp[m][n-1] - math.Cos(here.L.lat)*p[m][n-1] - ct[m][n]*dp[m][n-2]
			} else {
				p[m][n] = math.Sin(here.L.lat) * p[m][n-1]
				dp[m][n] = math.Sin(here.L.lat)*dp[m][n-1] - math.Cos(here.L.lat)*p[m][n-1]
			}

			fm := float64(m)
			sumz = sumz + p[m][n]*(g[m][n]*math.Cos(fm*here.L.lng)+h[m][n]*math.Sin(fm*here.L.lng))
			sumx = sumx + dp[m][n]*(g[m][n]*math.Cos(fm*here.L.lng)+h[m][n]*math.Sin(fm*here.L.lng))
			sumy = sumy + fm*p[m][n]*(g[m][n]*math.Sin(fm*here.L.lng)-h[m][n]*math.Cos(fm*here.L.lng))
		}

		fn := float64(n)
		fz = fz + math.Pow(ar, fn+2)*(fn+1)*sumz
		fx = fx - math.Pow(ar, fn+2)*sumx
		fy = fy + math.Pow(ar, fn+2)*sumy
	}

	// dip and fH can only be calculated for 2 heights in this project
	if height == 100 {
		hr = hr100km
	} else if height == 300 {
		hr = hr300km
	}

	here.dip[hr] = math.Atan(fz / math.Sqrt(math.Pow(fx, 2)+math.Pow(fy/math.Cos(here.L.lat), 2)))
	here.fH[hr] = 2.8 * math.Sqrt(math.Pow(fx, 2)+math.Pow(fy/math.Cos(here.L.lat), 2)+math.Pow(fz, 2))
}
